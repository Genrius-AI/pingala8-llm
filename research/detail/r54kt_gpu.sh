#!/bin/bash
# r54kt GPU stage (run as: ~/repo/bin/job bash research/detail/r54kt_gpu.sh): ppl (r36_hfj protocol), KLD vs mainline Q8_0 base
# (ctx 512 x 12 chunks, pe52 protocol), paired llama-bench (pp512, tg128, -r 15, 3 rotated rounds). One lock hold keeps the arms in one run.
cd ~/repo || exit 1
source bin/cuda_env.sh
W=work/r54kt; L=logs; IK=ext/ik_llama.cpp/build-cuda/bin; SB=llama.cpp/build-cuda/bin; FB=research/kernels/llama_f44/build/bin
H=datasets/wikitext2_test_hfjoin.raw; K=$W/q8_kld_c512x12.bin
KT=$W/qwen3-4B-IQ2_KT-ik.gguf; XX=$W/qwen3-4B-IQ2_XXS-ik.gguf; Q8=$W/qwen3-4B-Q8_0.gguf   # regenerated by r54kt_cpu.sh with mainline llama-quantize from the f16
MX=work/r45b/4B-IQ2_XXS-r45b.gguf; MB=work/r51t/native/4B-pingala8-vrnative-00001-of-00002.gguf
NAT="GGML_F44=4 GGML_F44_BATCH=2 GGML_VR_NATIVE=1 GGML_VRC_V=5 GGML_VRC_NWP=8 GGML_VR_RL=1 GGML_VR_PRMG=1 GGML_VR_PPC=2"
free_gb() { df -BG --output=avail /mnt/c | tail -1 | tr -dc 0-9; }
echo "GPU_STAGE start $(date +%T) C: free $(free_gb) GB"
[ "$(free_gb)" -ge 12 ] || { echo "STOP: C: below 12 GB"; exit 3; }
ls -la $KT $XX $Q8 $MX $MB 2>&1 | awk '{print $5, $NF}'
# Idempotent (a retry skips finished steps). Run 1 (19:24) was killed by the GPU tripwire because a second-slot ablation build shared VRAM with the
# ik perplexity run, so: wait until the GPU is quiet before each heavy step, and sample VRAM for the record (logs/r54kt_vram.log).
vused() { nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits | head -1; }
vgate() { for i in $(seq 1 90); do [ "$(vused)" -le 3000 ] && return 0; sleep 20; done; echo "VGATE timeout, VRAM used $(vused) MiB"; return 1; }
( while :; do echo "$(date +%T) $(vused)" >> $L/r54kt_vram.log; sleep 5; done ) & VS=$!; trap 'kill $VS 2>/dev/null' EXIT
pplok() { grep -aq '\[73\][0-9]' "$1" 2>/dev/null; }

# ---- a. ppl, r36_hfj protocol (-c 2049 --ppl-stride 4095 => n_ctx 4096), ik build
for T in IQ2_KT IQ2_XXS; do
  M=$W/qwen3-4B-$T-ik.gguf; [ -f $M ] || { echo "MISSING $M"; continue; }
  pplok $L/r54kt_ppl_$T.log && { echo "PPL $T already complete"; continue; }
  vgate || exit 9
  $IK/llama-perplexity -f $H -c 2049 --ppl-stride 4095 -ngl 99 -m $M > $L/r54kt_ppl_$T.log 2>&1
  echo "PPL $T rc=$? last $(grep -a -o '\[[0-9]*\][0-9.]*' $L/r54kt_ppl_$T.log | tail -1) $(date +%T)"
done
# short sanity runs (ctx 512 x 8 chunks, GPU) so a CPU cross-check can be compared if the GPU numbers look broken
for T in IQ2_KT IQ2_XXS; do
  M=$W/qwen3-4B-$T-ik.gguf; [ -f $M ] || continue
  grep -aq 'Final estimate' $L/r54kt_sanity_gpu_$T.log 2>/dev/null && continue
  vgate || exit 9
  $IK/llama-perplexity -f $H -c 512 --chunks 8 -ngl 99 -m $M > $L/r54kt_sanity_gpu_$T.log 2>&1
  echo "SANITY_GPU $T rc=$? $(grep -a -o 'Final estimate: PPL = [0-9.]*' $L/r54kt_sanity_gpu_$T.log | tail -1)"
done

# ---- b. KLD: regenerate the base logits with MAINLINE llama.cpp from Q8_0 (the Oct-5 file was deleted by pe52_gpuA), then ik arms
grep -aq 'Final estimate' $L/r54kt_kld_base_q8.log 2>/dev/null || rm -f $K
if [ ! -f $K ]; then
  vgate || exit 9
  $SB/llama-perplexity -m $Q8 -f $H -c 512 --chunks 12 -ngl 99 --kl-divergence-base $K > $L/r54kt_kld_base_q8.log 2>&1
  echo "KLDBASE rc=$? bytes=$(stat -c %s $K 2>/dev/null) ppl $(grep -a -o 'Final estimate: PPL = [0-9.]*' $L/r54kt_kld_base_q8.log)"
fi
s=$(stat -c %s $K 2>/dev/null || echo 0); [ "$s" -lt 1000000000 ] || { echo "KLD file >= 1 GB, deleting"; rm -f $K; }
kld() {  # label model
  grep -aq 'Mean *KLD' $L/r54kt_kld_$1.log 2>/dev/null && { echo "KLD $1 already complete"; return; }
  vgate || exit 9
  $IK/llama-perplexity -m $2 --kl-divergence-base $K --kl-divergence -c 512 --chunks 12 -ngl 99 > $L/r54kt_kld_$1.log 2>&1
  echo "KLD $1 rc=$? $(grep -a -E 'Mean +KLD|99.0% +KLD|Same top p' $L/r54kt_kld_$1.log | tr -s ' ' | tr '\n' '|')"; }
if [ -f $K ]; then
  kld Q8_0_control $Q8
  [ -f $KT ] && kld IQ2_KT $KT
  [ -f $XX ] && kld IQ2_XXS $XX
fi
rm -f $K $Q8; echo "KLDBASE+Q8_0 deleted $(date +%T)"

# ---- c. paired speed: arms ikKT, ikXX (ik build), mnXX (mainline IQ2_XXS, F44 binary with GGML_F44=0), mB (Model B native, F44 binary)
# Same run, 3 rounds with rotated arm order, llama-bench -fa 1 -ctk f16 -ctv f16 -r 15, pp512 then tg128 per arm.
BL=$L/r54kt_bench; mkdir -p $BL
idle() { for i in $(seq 1 20); do ok=1; for j in 1 2 3; do u=$(nvidia-smi --query-gpu=utilization.gpu --format=csv,noheader,nounits | head -1); [ "${u:-100}" -lt 8 ] || ok=0; sleep 2; done; [ $ok = 1 ] && return 0; sleep 24; done; return 1; }
ARMS="ikKT ikXX mnXX mB"; read -a AR <<< "$ARMS"; n=${#AR[@]}
run() {  # arm test round
  local a=$1 t=$2 p=$3 bin m e args f
  case $a in ikKT) bin=$IK; m=$KT; e="env";; ikXX) bin=$IK; m=$XX; e="env";; mnXX) bin=$FB; m=$MX; e="env GGML_F44=0";; mB) bin=$FB; m=$MB; e="env $NAT";; esac
  [ -f $m ] || { echo "BENCH $a missing model"; return; }
  [ $t = pp512 ] && args="-p 512 -n 0" || args="-p 0 -n 128"
  f=$BL/${a}_${t}_r$p
  grep -aq samples_ts $f.json 2>/dev/null && { echo "BENCH arm=$a test=$t round=$p already done"; return; }
  echo "PRE arm=$a test=$t round=$p $(nvidia-smi --query-gpu=utilization.gpu,clocks.sm,power.draw,temperature.gpu,memory.used --format=csv,noheader,nounits | head -1)" >> $BL/pre.log
  $e $bin/llama-bench -m $m -ngl 99 -fa 1 -ctk f16 -ctv f16 $args -r 15 -o json > $f.json 2> $f.err
  echo "BENCH arm=$a test=$t round=$p rc=$?"
}
for p in 1 2 3; do
  vgate || exit 9; idle && echo "ROUND $p idle $(date +%T)" || echo "ROUND $p CONTENDED (GPU util >= 8% for 10 min) $(date +%T)"
  for ((k = 0; k < n; k++)); do idx=$(( (k + p - 1) % n )); for t in pp512 tg128; do run "${AR[$idx]}" $t $p; done; done
done
echo "GPU_STAGE end $(date +%T)"
